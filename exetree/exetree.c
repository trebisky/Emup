#include <stdio.h>
#include <stdlib.h>
#include <string.h>

// 30284 lines
char *infile = "epp512_lm.raw";

/* The idea here is to work up a call graph.
 * We start with some function, then follow
 * the instructions until we encounter a RET
 * or a JMP that definitely ends the flow.
 *
 * We make a list of all calls and all
 * conditional jumps we encounter.
 * Conditional jumps must be investiaged.
 * They may lead to already visited code
 * or to new code that should be followed.
 *
 * We handle jumps and calls breadth first.
 * First of all we deal with jumps, exploring
 * new code if any is indicated, adding to
 * the jump and call lists.
 *
 * Next we follow the calls to develop a
 * call tree.
 *
 * Part of the game is to discover both dead
 * code that is never visited, and to identify
 * areas of data (including strings) that have
 * been mis-disassembled as code.
 *
 * The first function is interesting if it is
 * the "main" function for the program.
 * It won't simply end in a RET like any other
 * function, or is unlikely to.
 * (Perhaps it will if it is a function generated
 *  by a C compiler, but there will probably
 *  not be a path to that return).
 *
 * This program works from a text file containing
 * disassembly generated by ndisasm.
 * The basic datastructure is set up as an array
 * of lines from this file.  This avoids all the
 * issues involved with variable length instructions.
 *
 * For some reason, I see a lot of stupid code
 * that looks like this:
 *
 *		jl 0x119
 *		jmp 0x139
 *  119:
 *		code
 *  139:
 *
 * This would be better generated as:
 *
 *		jnl 0x139
 *		code
 *  139:
 *
 * This kind of thing tells you that you are dealing
 * with compiler generated code, and not a very good
 * compiler at that.
 */

// The biggest so far is 67 bytes
#define MAXLINE	100

// We have seen 8 believe it or not
#define MAXOP	10

// Max so far is 23
#define MAXARG	32

#define MAX_CALLS	100
#define MAX_JUMPS	100

struct line {
	char orig[MAXLINE];
	int addr;
	char opcode[MAXOP];
	char arg[MAXARG];
	char extra_arg[MAXARG];
	int is_jump;
	int is_ujump;
	int is_call;
	int is_ret;
	int visited;
	int has_arg;
	int has_extra;
	struct line *calls[MAX_CALLS];
	int ncalls;
	struct line *jumps[MAX_JUMPS];
	int njumps;
};

#define MAXLINES	40000
struct line lines[MAXLINES];
int nlines;

int max = 0;
// int max = 99;

/* ------------------------------------------------ */
/* "library" routines */

static void
error ( char *msg )
{
	fprintf ( stderr, "%s\n", msg );
	exit (1);
}

/* split a string in place.
 * tosses nulls into string, trashing it.
 */
int
split ( char *buf, char **bufp, int max )
{
    int i;
    char *p;

    p = buf;
    for ( i=0; i<max; ) {
        while ( *p && *p == ' ' )
            p++;
        if ( ! *p )
            break;
        bufp[i++] = p;
        while ( *p && *p != ' ' )
            p++;
        if ( ! *p )
        break;
        *p++ = '\0';
    }

    return i;
}

// works for me and short
int
hex ( char *str )
{
	return strtol ( str, NULL, 16 );
}

/* ------------------------------------------------ */

// The most we have seen is 6
// The minimum is 3
#define MAXW	8

static void
save_line ( char *ll )
{
	// char *p;
	struct line *lp;
	int size;
	char *wp[MAXW];
	int nw;

	// lp = (struct line *) = malloc ( sizeof(struct line) );
	size = strlen(ll) + 1;
	// p = malloc ( size );
	// if ( size > max )
	// 	max = size;

	lp = &lines[nlines];
	lp->is_jump = 0;
	lp->is_ujump = 0;
	lp->is_call = 0;
	lp->is_ret = 0;
	lp->has_arg = 0;
	lp->has_extra = 0;
	lp->visited = 0;

	strcpy ( lp->orig, ll );

	nw = split ( ll, wp, MAXW );
	if ( nw < 3 )
		error ( "Evil line" );
	// if ( nw < max )
	// 	max = nw;

	lp->addr = hex ( wp[0] );

	strcpy ( lp->opcode, wp[2] );

	// is there an extra arg?
	// we only deal with one, there could be more
	if ( nw > 4 ) {
		lp->has_extra = 1;
		strcpy ( lp->extra_arg, wp[4] );
	}

	// has one (or more) args
	if ( nw > 3 ) {
		lp->has_arg = 1;
		strcpy ( lp->arg, wp[3] );
		size = strlen ( wp[3] );
		if ( size > max )
			max = size;
	}

	// "jmp" is unconditional -- Ujump
	// all unconditional jumps are also flagged as jumps
	if ( lp->opcode[0] == 'j' )
		lp->is_jump = 1;
	if ( strncmp ( lp->opcode, "jmp", 3 ) == 0 )
		lp->is_ujump = 1;

	if ( strcmp ( lp->opcode, "call" ) == 0 )
		lp->is_call = 1;
	if ( strncmp ( lp->opcode, "ret", 3 ) == 0 )
		lp->is_ret = 1;

	nlines++;
}

static void
loadfile ( char *path )
{
	FILE *ff;
	char lbuf[MAXLINE];

	ff = fopen ( infile, "r" );
	if ( ff == NULL )
		error ( "Cannot open input" );

	nlines = 0;
	// remember -- fgets reads the newline
	while ( fgets ( lbuf, MAXLINE, ff ) ) {
		// ditch trailing newline
		lbuf[strcspn(lbuf, "\n")] = 0;
		save_line ( lbuf );
	}

	// printf ( "%d lines loaded\n", nlines );
	// printf ( "%d max length\n", max );
	fclose ( ff );
}

