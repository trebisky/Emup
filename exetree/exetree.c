// The most we have seen is 6
// The minimum is 3
#define MAXW	8

static void
save_line ( char *ll )
{
	// char *p;
	struct line *lp;
	int size;
	char *wp[MAXW];
	int nw;
	char pig[256];

	// lp = (struct line *) = malloc ( sizeof(struct line) );
	size = strlen(ll) + 1;
	// p = malloc ( size );
	// if ( size > max )
	// 	max = size;

	lp = &lines[nlines];
	lp->is_jump = 0;
	lp->is_ujump = 0;
	lp->is_call = 0;
	lp->is_ret = 0;
	lp->has_arg = 0;
	lp->n_extra = 0;
	lp->visited = 0;

	strcpy ( lp->orig, ll );

	strcpy ( pig, ll );
	nw = split ( ll, wp, MAXW );
	if ( nw < 3 )
		error ( "Evil line" );

	/* The biggest line we see has 6 words.
	 * Here it is:
	 * 00000006  9A90266F01        call word 0x16f:word 0x2690
	if ( nw > max ) {
		printf ( "NW: %s\n", pig );
		max = nw;
	}
	*/

	lp->addr = hex ( wp[0] );

	strcpy ( lp->opcode, wp[2] );

	// We can handle 2 extra arguments
	if ( nw > 6 )
		error ( "Whoa dude, line too complex" );

	// extra arguments?
	if ( nw > 4 ) {
		lp->n_extra = nw - 4;
		strcpy ( lp->extra1, wp[4] );
		if ( nw > 5 )
			strcpy ( lp->extra2, wp[5] );
	}

	// has one (or more) args
	if ( nw > 3 ) {
		lp->has_arg = 1;
		strcpy ( lp->arg, wp[3] );
		// size = strlen ( wp[3] );
		// if ( size > max )
		// 	max = size;
	}

	// "jmp" is unconditional -- Ujump
	// all unconditional jumps are also flagged as jumps
	if ( lp->opcode[0] == 'j' )
		lp->is_jump = 1;
	if ( strncmp ( lp->opcode, "jmp", 3 ) == 0 )
		lp->is_ujump = 1;

	if ( strcmp ( lp->opcode, "call" ) == 0 )
		lp->is_call = 1;
	if ( strncmp ( lp->opcode, "ret", 3 ) == 0 )
		lp->is_ret = 1;

	nlines++;
}

static void
loadfile ( char *path )
{
	FILE *ff;
	char lbuf[MAXLINE];

	ff = fopen ( infile, "r" );
	if ( ff == NULL )
		error ( "Cannot open input" );

	nlines = 0;
	// remember -- fgets reads the newline
	while ( fgets ( lbuf, MAXLINE, ff ) ) {
		// ditch trailing newline
		lbuf[strcspn(lbuf, "\n")] = 0;
		save_line ( lbuf );
	}

	// printf ( "%d lines loaded\n", nlines );
	// printf ( "%d max length\n", max );
	fclose ( ff );
}

