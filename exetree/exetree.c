/* We pipe this output to sort | uniq to get:
 * jmp
 * ja jna jc jnc
 * jg jng jl jnl
 * jo jno js jns
 * jz jnz 
 * jpe jpo, js
 * jcxz
 */

static void
alljumps ( void )
{
	int i;

	for ( i=0; i<nlines; i++ ) {
		if ( lines[i].is_jump )
			printf ( "%s\n", lines[i].opcode );
	}
}

/* A note on "call" lines, we see the following variety:
 *	call 0x16f:0x2836
 *	call 0x3f6d
 *	call far [ss:0x303a]
 *	call far [0x303a]
 *	call far [di]
 */

static int
find_addr ( int addr )
{
	int i;

	for ( i=0; i<nlines; i++ ) {
		if ( lines[i].addr == addr )
			return i;
	}
	error ( "Cannot find address" );
}

#define INVALID		0x0fffffff

/* Return the address embedded in a jump instruction
 */
static int
jump_addr ( struct line *lp )
{
	if ( ! lp->has_arg ) {
		printf ( "Weird jump: %s\n", lp->orig );
		return INVALID;
	}

	if ( lp->has_extra ) {
		if ( strcmp ( lp->arg, "short" ) == 0 )
			return ( hex(lp->extra_arg) );
		else
			printf ( "Weird jump: %s\n", lp->orig );
		return INVALID;
	}

	return ( hex(lp->arg) );
}

static void
chase ( int start, int verbose )
{
	int nn;
	struct line *lp;
	struct line *top;
	int i;

	if ( start == INVALID )
		return;

	nn = find_addr ( start );
	top = &lines[nn];

	top->ncalls = 0;
	top->njumps = 0;

	for ( lp=top; ; lp++ ) {
		// We have been here already
		if ( lp->visited ) {
			printf ( "Already been to %x\n", lp->addr );
			return;
		}

		lp->visited = 1;
		if ( lp->is_call ) {
			top->calls[top->ncalls++] = lp;
			printf ( "%s\n", lp->orig );
			continue;
		}
		if ( lp->is_jump ) {
			top->jumps[top->njumps++] = lp;
			printf ( "%s\n", lp->orig );
			continue;
		}
		if ( verbose )
			printf ( "%s\n", lp->orig );

		if ( lp->is_ret ) {
			printf ( "%s\n", lp->orig );
			break;
		}
		if ( lp->is_ujump ) {
			printf ( "%s\n", lp->orig );
			break;
		}
	}

	printf ( "%d calls\n", top->ncalls ); 
	printf ( "%d jumps\n", top->njumps ); 

	for ( i=0; i<top->njumps; i++ ) {
		printf ( "Jump: %s\n", top->jumps[i]->orig );
		// recursion
		chase ( jump_addr ( top->jumps[i] ), 1 );
	}

	for ( i=0; i<top->ncalls; i++ ) {
		printf ( "Call: %s\n", top->calls[i]->orig );
	}
}

int
main ( int argc, char **argv )
{
	loadfile ( infile );
	// alljumps ();
	chase ( 0x3da4, 0 );

	exit (0);
}

