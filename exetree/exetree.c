/* We pipe this output to sort | uniq to get:
 * jmp
 * ja jna jc jnc
 * jg jng jl jnl
 * jo jno js jns
 * jz jnz 
 * jpe jpo, js
 * jcxz
 */

static void
alljumps ( void )
{
	int i;

	for ( i=0; i<nlines; i++ ) {
		if ( lines[i].is_jump )
			printf ( "%s\n", lines[i].opcode );
	}
}

/* A note on "call" lines, we see the following variety:
 *	call 0x16f:0x2836
 *	call 0x3f6d
 *	call far [ss:0x303a]
 *	call far [0x303a]
 *	call far [di]
 */

static int
find_addr ( int addr )
{
	int i;

	for ( i=0; i<nlines; i++ ) {
		if ( lines[i].addr == addr )
			return i;
	}
	error ( "Cannot find address" );
}

#define INVALID		0x0fffffff

/* Return the address embedded in a JUMP instruction
 */
static int
jump_addr ( struct line *lp )
{
	if ( ! lp->has_arg ) {
		printf ( "Weird jump: %s\n", lp->orig );
		return INVALID;
	}

	if ( lp->n_extra > 0 ) {
		if ( strcmp ( lp->arg, "short" ) == 0 )
			return ( hex(lp->extra1) );
		else
			printf ( "Weird jump: %s\n", lp->orig );
		return INVALID;
	}

	if ( lp->arg[0] == '[' ) {
		printf ( "Weird jump: %s\n", lp->orig );
		return INVALID;
	}

	return ( hex(lp->arg) );
}

/* Return the address embedded in a CALL instruction
 */
static int
call_addr ( struct line *lp )
{
	char *div;
	int seg, off, adr;

	if ( ! lp->has_arg ) {
		printf ( "Weird call: %s\n", lp->orig );
		return INVALID;
	}

	if ( lp->n_extra != 2 ) {
		printf ( "Weird call: %s\n", lp->orig );
		return INVALID;
	}

	/* Code that worked for the old way.
	 *		call 0x16f:0x281f
	div = strchr ( lp->arg, ':' );
	if ( div == NULL ) {
		// printf ( "Weird call: %s\n", lp->orig );
		return ( hex(lp->arg) );
	}
	seg = hex ( lp->arg );
	off = hex ( div+1 );
	*/

	/* Code that works for the new way.
	 *		call word 0x16f:word 0x281f
	 */
	seg = hex ( lp->extra1 );
	off = hex ( lp->extra2 );

	adr = (seg<<4) + off;

	// printf ( "call addr: %x %x --> %x\n", seg, off, adr );
	// error ( "not really" );

	return ( adr );
}

static void
chase ( int start, struct line *from, int is_call, int verbose )
{
	int nn;
	struct line *lp;
	struct line *top;
	int i;

	if ( start == INVALID )
		return;

	nn = find_addr ( start );
	top = &lines[nn];

	if ( is_call ) {
		if ( from == NULL )
			printf ( "** CHASE --- call (initial)\n" );
		else
			printf ( "** CHASE call from: %s\n", from->orig );
	} else {
		if ( from == NULL )
			printf ( "** CHASE --- follow jump (initial)\n" );
		else
			printf ( "** CHASE follow jump from: %s\n", from->orig );
	}

	top->ncalls = 0;
	top->njumps = 0;

	for ( lp=top; ; lp++ ) {
		// We have been here already
		if ( lp->visited ) {
			printf ( "Already been to %x\n", lp->addr );
			return;
		}

		lp->visited = 1;

		if ( lp->is_call ) {
			// XXX - check and skip if already traversed
			top->calls[top->ncalls++] = lp;
			printf ( "%s\n", lp->orig );
			continue;
		}

		// Must be before general jump check below
		if ( lp->is_ujump ) {
			top->jumps[top->njumps++] = lp;
			printf ( "%s\n", lp->orig );
			printf ( " BREAK on jmp\n" );
			break;
		}

		if ( lp->is_jump ) {
			top->jumps[top->njumps++] = lp;
			printf ( "%s\n", lp->orig );
			continue;
		}

		if ( verbose )
			printf ( "%s\n", lp->orig );

		if ( lp->is_ret ) {
			printf ( "%s\n", lp->orig );
			printf ( " BREAK on ret\n" );
			break;
		}
	}

	printf ( "%d jumps\n", top->njumps ); 
	printf ( "%d calls\n", top->ncalls ); 

	for ( i=0; i<top->njumps; i++ ) {
		printf ( "Jump: %s\n", top->jumps[i]->orig );
		// recursion
		chase ( jump_addr ( top->jumps[i] ), top->jumps[i], 0, 1 );
	}

	for ( i=0; i<top->ncalls; i++ ) {
		printf ( "Call: %s\n", top->calls[i]->orig );
		chase ( call_addr ( top->calls[i] ), top->calls[i], 1, 1 );
	}
}

/* Report on address ranges visited and not visited */
static void
report ( void )
{
	int i;
	struct line *lp;
	struct line *start;
	struct line *last;
	int nvisit = 0;
	int state = 0;

	for ( i=0; i<nlines; i++ ) {
		lp = &lines[i];
		if ( lp->visited )
			nvisit++;
	}

	printf ( "\n\n" );
	printf ( "%d lines of %d visited\n", nvisit, nlines );

	for ( i=0; i<nlines; i++ ) {
		lp = &lines[i];
		if ( lp->visited != state ) {
			if ( lp->visited ) {
				start = lp;
			} else {
				printf ( "Visited: %x to %x\n", start->addr, last->addr );
			}
			state = lp->visited;
		}
		last = lp;
	}
}

int
main ( int argc, char **argv )
{
	loadfile ( infile );
	// alljumps ();
	chase ( 0x3da4, NULL, 1, 0 );
	report ();

	exit (0);
}

